"""Verify a CSV export made by scripts/export_csv_subset.py and write its index and README (Python stdlib only).

Checks: every session in export_manifest.jsonl exists exactly once; both CSV files exist and their SHA-256 and byte
size equal the values recorded when they were written on the source machine; no unexpected CSV files; optional
expected session / frame counts. Writes index.csv (one row per session) and README.md into the export directory.

Usage: python3 scripts/verify_csv_export.py EXPORT_DIR [--expect-sessions 167] [--expect-frames 88858703]
"""

from __future__ import annotations

import argparse
import csv
import hashlib
import json
import sys
from collections import Counter
from pathlib import Path


def sha256(p: Path) -> str:
    h = hashlib.sha256()
    with open(p, "rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


README = """# fleetcan-sim-scale-1.0 — CSV export (repetition R1 of every configuration)

Plain-CSV copy of {sessions} sessions ({frames:,} CAN frames) of the frozen dataset fleetcan-sim-scale-1.0, one session per
configuration (repetition 1 of 5), produced by `scripts/export_csv_subset.py` from the frozen Parquet files. Every value was
checked against the Parquet source when written, and every file against its SHA-256 here (`scripts/verify_csv_export.py`).
The authoritative dataset remains the frozen Parquet release (`dataset-fleetcan-sim-scale-1.0`).

## Folder structure (scenario / attack / fleet size)

```
<scenario>/<attack>/N<NNN>/<session_id>_can_frames.csv   raw observable CAN frames (one row per frame)
<scenario>/<attack>/N<NNN>/<session_id>_labels.csv       per-frame ground truth, joined on frame_uid
```

| Scenario folder | Meaning |
|---|---|
| S0_benign | no attack |
| S1_isolated | one attacked vehicle |
| S2_independent | several independent attacks (coordinated = false), timing near-simultaneous / 0.5 s / 10 s |
| S3_coordinated | one coordinated campaign of K vehicles (simultaneous, 0.5/2/10 s stagger, partial overlap, bounded spread) |
| S3_mixed | coordinated campaign + unrelated independent attacks |
| S3_replay_probe | 0.1 s replay timing probe (K = 2) |

Attack folders: none, flooding, fuzzy, malfunction, replay. Fleet folders: N020, N050, N100, and N010 (= the G0
route-source bridge sessions). The session id encodes N, scenario, attack, K and timing, for example
`FCS10_N100_S3_replay_K100_simultaneous_R1`. `index.csv` lists every session with N, K, scenario, attack, timing, seed,
frame count, file paths and SHA-256.

## Columns

`*_can_frames.csv` (observable): frame_uid, session_id, scenario_id, timestamp (s), sim_time_ns, transmission_timestamp (s),
tx_start_ns, tx_end_ns, queue_delay_us, frame_bits, capture_time_ns, capture_offset_us, vehicle_id, channel, can_id (hex),
dlc, payload (hex).

`*_labels.csv` (ground truth, evaluation only): frame_uid, session_id, frame_label (benign / malicious), attack_type,
campaign_id, attack_id, frame_source, message_name. `None` = not applicable.

## Detector-safe use

Use only observable fields of `*_can_frames.csv` as detector input (timestamps, vehicle_id/channel, can_id, dlc, payload).
`scenario_id`, `session_id`, `frame_uid` and everything in `*_labels.csv` must not be detector features; join the labels
only for evaluation. This is a synthetic CAN dataset generated by the SUMO + synthetic CAN testbed, not real vehicle data.
"""


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("export_dir")
    ap.add_argument("--expect-sessions", type=int)
    ap.add_argument("--expect-frames", type=int)
    a = ap.parse_args()
    d = Path(a.export_dir).expanduser()
    recs = [json.loads(l) for l in (d / "export_manifest.jsonl").read_text().splitlines() if l.strip()]
    dup = [k for k, v in Counter(r["session_id"] for r in recs).items() if v > 1]
    bad = []
    for i, r in enumerate(recs):
        for kind in ("can_frames", "labels"):
            p = d / r[f"{kind}_csv"]
            if not p.exists() or p.stat().st_size != r[f"{kind}_bytes"] or sha256(p) != r[f"{kind}_sha256"]:
                bad.append(str(p))
        if (i + 1) % 25 == 0:
            print(f"verified {i + 1}/{len(recs)} sessions", flush=True)
    listed = {r[f"{k}_csv"] for r in recs for k in ("can_frames", "labels")}
    on_disk = {str(p.relative_to(d)) for p in d.rglob("*.csv") if p.name != "index.csv"}
    extra, missing = sorted(on_disk - listed), sorted(listed - on_disk)
    frames = sum(r["frames"] for r in recs)
    ok = (not bad and not dup and not extra and not missing
          and (a.expect_sessions is None or len(recs) == a.expect_sessions)
          and (a.expect_frames is None or frames == a.expect_frames))
    cols = ["session_id", "config_id", "repetition", "seed", "phase", "purpose", "N", "K", "scenario", "attack", "timing",
            "independent_attack_count", "mixed_attack_count", "duration_s", "frames", "can_frames_csv", "can_frames_sha256",
            "labels_csv", "labels_sha256"]
    with open(d / "index.csv", "w", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=cols, extrasaction="ignore")
        w.writeheader()
        w.writerows(sorted(recs, key=lambda r: r["can_frames_csv"]))
    (d / "README.md").write_text(README.format(sessions=len(recs), frames=frames))
    size = sum(p.stat().st_size for p in d.rglob("*.csv"))
    print(json.dumps({"sessions": len(recs), "frames": frames, "csv_files": len(on_disk), "bytes": size,
                      "by_scenario": dict(Counter(r["scenario"] for r in recs)), "by_N": dict(Counter(r["N"] for r in recs)),
                      "checksum_or_size_mismatch": bad[:10], "duplicates": dup, "unexpected_files": extra[:10],
                      "missing_files": missing[:10], "verdict": "PASS" if ok else "FAIL"}, indent=1))
    sys.exit(0 if ok else 1)


if __name__ == "__main__":
    main()
