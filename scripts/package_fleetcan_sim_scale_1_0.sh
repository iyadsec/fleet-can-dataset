#!/usr/bin/env bash
# Milestone 11: package the FROZEN fleetcan-sim-scale-1.0 into deterministic split tar + zstd parts.
# Read-only on the source: files are only read; nothing under data/ is created, renamed or touched.
#
# Archive content: every file listed in data/final/fleetcan-sim-scale-1.0/SHA256SUMS (26,740 files) plus
# SHA256SUMS and FREEZE.json themselves, stored under  fleetcan-sim-scale-1.0/data/<path relative to data/>
# (the exact on-disk layout), in byte-wise sorted order; POSIX (pax) tar, owner/group 0, numeric ids,
# atime/ctime not stored, original mtime and mode kept; zstd level 3 (lossless; Parquet is already compressed);
# split into parts of 1,610,612,736 bytes (1.5 GiB; GitHub release assets must be < 2 GiB).
#
# Usage: scripts/package_fleetcan_sim_scale_1_0.sh [OUTPUT_DIR]   (default ~/fleetcan_exports/fleetcan-sim-scale-1.0)
set -euo pipefail

NAME=fleetcan-sim-scale-1.0
SUMS_SHA=5d5418b1ca9a4107818a83e03a5dea4a4ea83d1c36354fa668fcc5cb0242de70
MATRIX_SHA=9fc005de3f9b712045c7eec5c610043a375ab2dad362fff5b54a092a17a1e735
PART_BYTES=1610612736
ZSTD_LEVEL=3
ZSTD_THREADS=4
REPO="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
DATA="$REPO/data"
FINAL="$DATA/final/$NAME"
OUT="${1:-$HOME/fleetcan_exports/$NAME}"

die() { echo "STOP: $*" >&2; exit 1; }
[[ "$OUT" != "$DATA"* ]] || die "output directory must be outside data/"
[ "$(sha256sum "$FINAL/SHA256SUMS" | cut -c1-64)" = "$SUMS_SHA" ] || die "SHA256SUMS digest differs from the frozen value"
[ "$(sha256sum "$REPO/configs/fleetcan_sim_scale_1_0.yaml" | cut -c1-64)" = "$MATRIX_SHA" ] || die "matrix SHA differs"
[ -z "$(git -C "$REPO" status --porcelain --untracked-files=no)" ] || die "repository has modified tracked files"
mkdir -p "$OUT"
[ -z "$(ls -A "$OUT")" ] || die "output directory $OUT is not empty"

LIST="$OUT/$NAME-filelist.txt"
{ awk '{print $2}' "$FINAL/SHA256SUMS"; echo "final/$NAME/SHA256SUMS"; echo "final/$NAME/FREEZE.json"; } | LC_ALL=C sort > "$LIST"
grep -q ' ' "$LIST" && die "unexpected whitespace in a path"
NFILES=$(wc -l < "$LIST")

echo "packaging $NFILES files into $OUT"
tar -C "$DATA" --no-recursion --verbatim-files-from --files-from="$LIST" \
    --format=posix --pax-option='exthdr.name=%d/PaxHeaders/%f,delete=atime,delete=ctime' \
    --owner=0 --group=0 --numeric-owner --transform="s,^,$NAME/data/," -cf - \
  | zstd -"$ZSTD_LEVEL" -T"$ZSTD_THREADS" -q -c \
  | split -b "$PART_BYTES" -d -a 3 --numeric-suffixes=1 - "$OUT/$NAME.tar.zst.part"

(cd "$OUT" && sha256sum "$NAME".tar.zst.part* > "$NAME-archive-SHA256SUMS")

python3 - "$OUT" "$NAME" "$REPO" "$NFILES" <<'EOF'
import json, os, subprocess, sys
out, name, repo, nfiles = sys.argv[1], sys.argv[2], sys.argv[3], int(sys.argv[4])
freeze = json.load(open(os.path.join(repo, "data", "final", name, "FREEZE.json")))
parts = []
for line in open(os.path.join(out, f"{name}-archive-SHA256SUMS")):
    sha, fn = line.split()
    parts.append({"file": fn, "bytes": os.path.getsize(os.path.join(out, fn)), "sha256": sha})
ver = lambda *c: subprocess.run(c, capture_output=True, text=True).stdout.strip().splitlines()[0]
rel = {
    "dataset": name, "dataset_version": name, "release_tag": f"dataset-{name}", "repository": "iyadsec/fleet-can-dataset",
    "description": "synthetic CAN dataset generated by the SUMO + synthetic CAN testbed: raw observable CAN data + separate "
                   "ground truth; no precomputed FLEET-GUARD descriptors",
    "sessions": freeze["sessions"], "configurations": freeze["configurations"], "repetitions": 5, "frames": 444333222,
    "source_files_hashed": freeze["files_hashed"], "source_bytes_hashed": freeze["total_bytes"],
    "archived_files": nfiles, "archived_extra_files": ["final/" + name + "/SHA256SUMS", "final/" + name + "/FREEZE.json"],
    "matrix_id": freeze["matrix_id"], "matrix_sha256": freeze["matrix_sha256"],
    "dataset_SHA256SUMS_sha256": freeze["sha256sums_sha256"], "dataset_FREEZE_json_sha256":
        subprocess.run(["sha256sum", os.path.join(repo, "data", "final", name, "FREEZE.json")], capture_output=True, text=True).stdout[:64],
    "generator_version": freeze["generator_version"], "schema_version": freeze["schema_version"],
    "generator_commits": freeze["generator_commits"],
    "archive": {"format": "tar (POSIX pax, sorted, owner/group 0)", "compression": "zstd -3 (lossless)", "split_bytes": 1610612736,
                "root": f"{name}/data/", "part_count": len(parts), "total_bytes": sum(p["bytes"] for p in parts), "parts": parts,
                "archive_SHA256SUMS": f"{name}-archive-SHA256SUMS",
                "tools": {"tar": ver("tar", "--version"), "zstd": ver("zstd", "--version"), "split": ver("split", "--version")}},
    "creation_git_commit": subprocess.run(["git", "-C", repo, "rev-parse", "HEAD"], capture_output=True, text=True).stdout.strip(),
    "restore": "scripts/download_fleetcan_sim_scale_1_0.sh <destination>",
}
json.dump(rel, open(os.path.join(out, f"{name}-release.json"), "w"), indent=1)
print(json.dumps({k: rel[k] for k in ("sessions", "archived_files", "creation_git_commit")}), len(parts), "parts")
EOF
ls -l "$OUT"
