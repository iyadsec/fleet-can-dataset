"""Experiment metadata and configuration snapshot for reproducibility."""

from __future__ import annotations

import hashlib
import json
import platform
import shutil
import subprocess
import sys
from importlib import metadata as im
from pathlib import Path

from .config import PROJECT_ROOT, ExperimentConfig

TRACKED_PACKAGES = ["eclipse-sumo", "traci", "sumolib", "python-can", "cantools",
                    "pandas", "numpy", "PyYAML", "pytest"]


def sha256(path: Path) -> str:
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def git_info(root: Path = PROJECT_ROOT) -> dict:
    def run(*args):
        r = subprocess.run(["git", *args], cwd=root, capture_output=True, text=True)
        return r.stdout.strip() if r.returncode == 0 else None
    commit = run("rev-parse", "HEAD")
    status = run("status", "--porcelain", "--untracked-files=no")
    return {"commit": commit, "dirty": bool(status) if status is not None else None}


def package_versions() -> dict:
    out = {}
    for p in TRACKED_PACKAGES:
        try:
            out[p] = im.version(p)
        except im.PackageNotFoundError:
            out[p] = None
    return out


def snapshot_configs(cfg: ExperimentConfig, dest: Path) -> dict:
    """Copy every config/DBC/SUMO input file into the session folder and hash it."""
    dest.mkdir(parents=True, exist_ok=True)
    files = dict(cfg.source_files)
    sumo_dir = cfg.sumo_config.parent
    files[f"sumo/{cfg.sumo_config.name}"] = cfg.sumo_config
    for p in sorted((sumo_dir.parent / "network").glob("*.xml")) + sorted((sumo_dir.parent / "routes").glob("*.xml")):
        files[f"sumo/{p.parent.name}/{p.name}"] = p
    hashes = {}
    for name, src in files.items():
        target = dest / name
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(src, target)
        hashes[name] = sha256(src)
    return hashes


