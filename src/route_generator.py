"""Deterministic, parameterised SUMO route generation for arbitrary fleet sizes (generator 1.2.0, M8).

New path only: used when an experiment sets `simulation.route_generation`. fleetcan-sim-1.1 configurations keep
their hand-written route files (`sumo/routes/fleet_{2,5,10}.rou.xml`) and are not affected.

Method `grid_loops_v1` makes the legacy mobility design parametric instead of redesigning it:
  * same network (sumo/network/grid4x4.net.xml), same vType `car_a`, every vehicle departs at t = 0 with speed 0
  * same three closed loops as the legacy routes: perimeter clockwise (P), perimeter counter-clockwise (R),
    inner signalised loop (I); a vehicle drives its loop repeatedly from its start edge
  * start positions: candidate slots every 30 m along every loop edge (10, 40, ..., <= length - 10 m), N slots drawn
    WITHOUT replacement with numpy default_rng(derive_seed(seed, "route_generation")) — so vehicles start at
    different places on different loops (no artificial synchronisation) and the draw is independent of every
    other random stream (profiles, switch-on, jitter, attacks, campaigns)
  * route length covers the configured duration with a 2x speed margin, so no vehicle leaves the network early
Validity checks: every edge exists, every consecutive edge pair is connected in the network, IDs unique,
N <= number of slots (168 on grid4x4).
"""

from __future__ import annotations

import hashlib
import math
import shutil
import xml.etree.ElementTree as ET
from pathlib import Path

import numpy as np

METHOD = "grid_loops_v1"
LOOPS: dict[str, list[str]] = {     # identical to the loops of the legacy route files (sumo/routes/fleet_10.rou.xml)
    "P": ["A0B0", "B0C0", "C0D0", "D0D1", "D1D2", "D2D3", "D3C3", "C3B3", "B3A3", "A3A2", "A2A1", "A1A0"],
    "R": ["A0A1", "A1A2", "A2A3", "A3B3", "B3C3", "C3D3", "D3D2", "D2D1", "D1D0", "D0C0", "C0B0", "B0A0"],
    "I": ["B1C1", "C1C2", "C2B2", "B2B1"],
}
SLOT_START_M, SLOT_SPACING_M, SLOT_END_MARGIN_M = 10.0, 30.0, 10.0
VTYPE = '<vType id="car_a" vClass="passenger" accel="2.6" decel="4.5" sigma="0.5" length="4.5" maxSpeed="40"/>'
SUMOCFG = """<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by src/route_generator.py ({method}); step length, seed and end time are passed by the orchestrator. -->
<configuration>
    <input>
        <net-file value="../network/{net}"/>
        <route-files value="../routes/fleet.rou.xml"/>
    </input>
    <processing>
        <collision.action value="warn"/>
        <time-to-teleport value="-1"/>
    </processing>
    <report>
        <no-step-log value="true"/>
        <duration-log.disable value="true"/>
    </report>
</configuration>
"""


class RouteGenerationError(ValueError):
    pass


def read_network(net_path: Path) -> tuple[dict[str, tuple[float, float]], set[tuple[str, str]]]:
    """(edge -> (length_m, speed_mps)) for normal edges, and the set of (from_edge, to_edge) connections."""
    root = ET.parse(net_path).getroot()
    edges = {}
    for e in root.findall("edge"):
        if e.get("function") == "internal":
            continue
        lane = e.find("lane")
        edges[e.get("id")] = (float(lane.get("length")), float(lane.get("speed")))
    conns = {(c.get("from"), c.get("to")) for c in root.findall("connection") if not c.get("from", "").startswith(":")}
    return edges, conns


def slots(edges: dict[str, tuple[float, float]]) -> list[tuple[str, str, float]]:
    """All candidate start slots (loop, edge, departPos) in a fixed order."""
    out = []
    for loop, seq in LOOPS.items():
        for e in seq:
            length = edges[e][0]
            pos = SLOT_START_M
            while pos <= length - SLOT_END_MARGIN_M + 1e-9:
                out.append((loop, e, round(pos, 1)))
                pos += SLOT_SPACING_M
    return out


def validate_loops(edges, conns) -> None:
    for loop, seq in LOOPS.items():
        for a, b in zip(seq, seq[1:] + seq[:1]):
            if a not in edges or b not in edges:
                raise RouteGenerationError(f"loop {loop}: edge {a if a not in edges else b} not in network")
            if (a, b) not in conns:
                raise RouteGenerationError(f"loop {loop}: no connection {a} -> {b}")


def generate(net_path: Path, vehicle_ids: list[str], route_seed: int, duration_s: float) -> tuple[str, dict]:
    """Route-file XML and a provenance record. Pure function of (network, vehicle IDs, seed, duration)."""
    if len(set(vehicle_ids)) != len(vehicle_ids):
        raise RouteGenerationError("duplicate vehicle IDs")
    edges, conns = read_network(net_path)
    validate_loops(edges, conns)
    cand = slots(edges)
    n = len(vehicle_ids)
    if n > len(cand):
        raise RouteGenerationError(f"{n} vehicles exceed {len(cand)} start slots of {METHOD}")
    pick = np.random.default_rng(int(route_seed)).choice(len(cand), size=n, replace=False)
    routes, vehicles, assign = [], [], []
    for vid, k in zip(vehicle_ids, pick):
        loop, start, pos = cand[int(k)]
        seq = LOOPS[loop]
        i = seq.index(start)
        rot = seq[i:] + seq[:i]
        loop_len = sum(edges[e][0] for e in seq)
        vmax = max(edges[e][1] for e in seq)
        reps = math.ceil(duration_s * vmax * 2.0 / loop_len) + 1
        rid = f"r_{vid}"
        routes.append(f'    <route id="{rid}" edges="{" ".join(rot * reps)}"/>')
        vehicles.append(f'    <vehicle id="{vid}" type="car_a" route="{rid}" depart="0" departLane="0" '
                        f'departPos="{pos:.1f}" departSpeed="0"/>')
        assign.append({"vehicle_id": vid, "loop": loop, "start_edge": start, "depart_pos_m": pos, "loop_repetitions": reps})
    xml = "\n".join(['<?xml version="1.0" encoding="UTF-8"?>',
                     f'<!-- Generated by src/route_generator.py ({METHOD}), route_seed={int(route_seed)}, {n} vehicles. -->',
                     "<routes>", f"    {VTYPE}", *routes, *vehicles, "</routes>", ""])
    info = {"method": METHOD, "route_seed": int(route_seed), "vehicles": n, "candidate_slots": len(cand),
            "slot_spacing_m": SLOT_SPACING_M, "duration_s": duration_s, "loops": {k: len(v) for k, v in LOOPS.items()},
            "loop_counts": {k: sum(a["loop"] == k for a in assign) for k in LOOPS}, "assignment": assign,
            "route_sha256": hashlib.sha256(xml.encode()).hexdigest()}
    return xml, info


def write_scenario(out_dir: Path, net_path: Path, vehicle_ids: list[str], route_seed: int, duration_s: float) -> tuple[Path, dict]:
    """Write <out_dir>/{scenarios/fleet.sumocfg, routes/fleet.rou.xml, network/<net>} (same layout as sumo/)."""
    xml, info = generate(net_path, vehicle_ids, route_seed, duration_s)
    for d in ("scenarios", "routes", "network"):
        (out_dir / d).mkdir(parents=True, exist_ok=True)
    shutil.copy2(net_path, out_dir / "network" / net_path.name)
    (out_dir / "routes" / "fleet.rou.xml").write_text(xml)
    cfg = out_dir / "scenarios" / "fleet.sumocfg"
    cfg.write_text(SUMOCFG.format(method=METHOD, net=net_path.name))
    info["network"] = net_path.name
    info["network_sha256"] = hashlib.sha256(net_path.read_bytes()).hexdigest()
    return cfg, info
